#!/usr/bin/env bash
# Builds the OCI image and checks it: the gateway starts with an [auth]
# config, becomes healthy, answers /readyz, and rejects an unauthenticated
# request before any upstream contact (no provider call is made).
set -euo pipefail
cd "$(dirname "$0")/.."

image=${WYE_IMAGE:-wye:smoke}
port=${WYE_SMOKE_PORT:-18080}
# Under the checkout: Docker Desktop shares the home directory, not /var/folders.
mkdir -p target
work=$(mktemp -d "$PWD/target/image-smoke.XXXXXX")
name="wye-smoke-$$"
cleanup() { docker rm -f "$name" >/dev/null 2>&1 || true; command rm -rf "$work"; }
trap cleanup EXIT

docker build -t "$image" .
docker image inspect "$image" --format 'image size: {{.Size}} bytes'

# A throwaway verification key, generated by the image itself; only the
# printed public half is needed.
docker run --rm "$image" token keygen --out /tmp/issuer.key \
    | grep ed25519_public_key > "$work/key.toml"
cat > "$work/wye.toml" <<TOML
[server]
listen = "0.0.0.0:8080"
drain_delay_secs = 0

[upstream]
base_url = "https://api.anthropic.com"
api_key_env = "ANTHROPIC_API_KEY"

[auth]
issuer = "wye"
audience = "wye-smoke"
[[auth.keys]]
id = "k1"
$(cat "$work/key.toml")
TOML

docker run -d --name "$name" -p "127.0.0.1:$port:8080" \
    -v "$work/wye.toml:/etc/wye/wye.toml:ro" -e ANTHROPIC_API_KEY=sk-unused "$image" >/dev/null

for _ in $(seq 1 30); do
    status=$(docker inspect -f '{{.State.Health.Status}}' "$name")
    [ "$status" = healthy ] && break
    sleep 1
done
[ "$status" = healthy ] || { docker logs "$name"; echo "not healthy: $status"; exit 1; }

code=$(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$port/readyz")
[ "$code" = 200 ] || { echo "/readyz: $code"; exit 1; }
code=$(curl -s -o /dev/null -w '%{http_code}' -X POST "http://127.0.0.1:$port/v1/messages" -d '{}')
[ "$code" = 401 ] || { echo "unauthenticated request: $code"; exit 1; }
docker stop -t 10 "$name" >/dev/null
echo "image smoke test passed"
