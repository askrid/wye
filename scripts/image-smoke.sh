#!/usr/bin/env bash
# Checks the OCI image: its wye runs without a warning from the dynamic
# loader, and the gateway starts with an [auth] config, becomes healthy,
# answers /readyz, and rejects an unauthenticated request before any upstream
# contact (no provider call is made).
#
#   scripts/image-smoke.sh                     builds wye:smoke from this checkout
#   WYE_IMAGE=<image> scripts/image-smoke.sh   checks that image, pulled if not
#                                              local, without building
#
# WYE_SMOKE_PORT overrides the host port (18080).
set -euo pipefail
cd "$(dirname "$0")/.."

image=${WYE_IMAGE:-}
port=${WYE_SMOKE_PORT:-18080}
# Under the checkout: Docker Desktop shares the home directory, not /var/folders.
mkdir -p target
work=$(mktemp -d "$PWD/target/image-smoke.XXXXXX")
name="wye-smoke-$$"
cleanup() { docker rm -f "$name" >/dev/null 2>&1 || true; command rm -rf "$work"; }
trap cleanup EXIT

if [ -z "$image" ]; then
    image=wye:smoke
    docker build -t "$image" .
elif ! docker image inspect "$image" >/dev/null 2>&1; then
    docker pull "$image"
fi
docker image inspect "$image" --format 'image size: {{.Size}} bytes'

# A binary built against a newer glibc than the image's still starts when
# the newer symbols it uses are weak, but the loader warns on every run
# ("version `GLIBC_2.39' not found"); a release binary must not.
warnings=$(docker run --rm "$image" --version 2>&1 >/dev/null)
[ -z "$warnings" ] || { echo "wye --version wrote to stderr: $warnings"; exit 1; }

# A throwaway verification key, generated by the image itself; only the
# printed line with its public half is needed.
docker run --rm "$image" token keygen --out /tmp/signing.key \
    | grep '^signing_keys = ' > "$work/key.toml"
cat > "$work/wye.toml" <<TOML
[server]
listen = "0.0.0.0:8080"

[[upstreams]]
base_url = "https://api.anthropic.com"
provider_key = { env = "ANTHROPIC_API_KEY" }

[auth]
audience = "wye-smoke"
$(cat "$work/key.toml")
TOML

docker run -d --name "$name" -p "127.0.0.1:$port:8080" \
    -v "$work/wye.toml:/etc/wye/wye.toml:ro" -e ANTHROPIC_API_KEY=sk-unused "$image" >/dev/null

for _ in $(seq 1 30); do
    status=$(docker inspect -f '{{.State.Health.Status}}' "$name")
    [ "$status" = healthy ] && break
    sleep 1
done
[ "$status" = healthy ] || { docker logs "$name"; echo "not healthy: $status"; exit 1; }

code=$(curl -s --max-time 10 -o /dev/null -w '%{http_code}' "http://127.0.0.1:$port/readyz")
[ "$code" = 200 ] || { echo "/readyz: $code"; exit 1; }
code=$(curl -s --max-time 10 -o /dev/null -w '%{http_code}' -X POST "http://127.0.0.1:$port/v1/messages" -d '{}')
[ "$code" = 401 ] || { echo "unauthenticated request: $code"; exit 1; }
docker stop -t 10 "$name" >/dev/null
echo "image smoke test passed"
